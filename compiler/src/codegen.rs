//! Rust code generation. Input must be free of errors.
//!
//! Value model: Int -> i64, Bool -> bool, Text -> Rc<String>, List[T] -> Rc<Vec<T>>,
//! user types -> Rc<T_Name>. All values are immutable and shared; every read of a
//! variable is a (cheap) clone. `set x = f(x, ...)` moves `x` instead of cloning it
//! when that is unobservable, so building lists and text in loops is amortized O(1).

use std::collections::BTreeMap;
use std::fmt::Write;

use crate::ast::*;
use crate::diag::{SourceFile, Span};
use crate::runtime::PRELUDE;
use crate::types::{Type, TypeDef};

struct Gen<'a> {
    files: &'a [SourceFile],
    types: &'a [Type],
    defs: &'a BTreeMap<String, TypeDef>,
    fn_name: String,
    tmp: usize,
    take_var: Option<String>,
}

pub fn generate(program: &Program, files: &[SourceFile], types: &[Type], defs: &BTreeMap<String, TypeDef>) -> String {
    let mut g = Gen { files, types, defs, fn_name: String::new(), tmp: 0, take_var: None };
    let mut out = String::new();
    out.push_str("// Generated by the Tessera compiler. Do not edit.\n");
    out.push_str(PRELUDE);
    out.push('\n');
    for item in &program.items {
        match item {
            Item::Record(r) => {
                let _ = writeln!(out, "#[derive(Clone, PartialEq)]\nstruct T_{} {{", r.name);
                if let Some(TypeDef::Record { fields }) = defs.get(&r.name) {
                    for (name, ty) in fields {
                        let _ = writeln!(out, "    f_{}: {},", name, rust_type(ty));
                    }
                }
                out.push_str("}\n\n");
            }
            Item::Enum(e) => {
                let _ = writeln!(out, "#[derive(Clone, PartialEq)]\nenum T_{} {{", e.name);
                if let Some(TypeDef::Enum { variants }) = defs.get(&e.name) {
                    for (name, fields) in variants {
                        if fields.is_empty() {
                            let _ = writeln!(out, "    V_{},", name);
                        } else {
                            let tys: Vec<String> = fields.iter().map(|(_, t)| rust_type(t)).collect();
                            let _ = writeln!(out, "    V_{}({}),", name, tys.join(", "));
                        }
                    }
                }
                out.push_str("}\n\n");
            }
            Item::Function(_) => {}
        }
    }
    for item in &program.items {
        if let Item::Function(f) = item {
            out.push_str(&g.function(f));
            out.push('\n');
        }
    }
    out.push_str("fn main() {\n    t_run(f_main);\n}\n");
    out
}

pub fn rust_type(t: &Type) -> String {
    match t {
        Type::Int => "i64".into(),
        Type::Bool => "bool".into(),
        Type::Text => "Rc<String>".into(),
        Type::Unit | Type::Never | Type::Unknown => "()".into(),
        Type::List(inner) => format!("Rc<Vec<{}>>", rust_type(inner)),
        Type::Named(n) => format!("Rc<T_{}>", n),
    }
}

/// Rust string literal with a simple, fully specified escaping rule (shared with stage 1):
/// printable ASCII is kept, `"` and `\\` are escaped, `\n` `\r` `\t` use short escapes,
/// everything else becomes `\u{hex}`.
pub fn rust_string(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            ' '..='~' => out.push(c),
            _ => out.push_str(&format!("\\u{{{:x}}}", c as u32)),
        }
    }
    out.push('"');
    out
}

fn pad(ind: usize) -> String {
    "    ".repeat(ind)
}

/// Facts about how a variable is used inside an expression.
#[derive(Default)]
struct Usage {
    count: usize,
    has_jump_or_loop: bool,
}

fn scan_block(b: &Block, var: &str, u: &mut Usage) {
    for s in &b.stmts {
        match s {
            Stmt::Let { value, .. } | Stmt::Set { value, .. } => scan(value, var, u),
            Stmt::Expr(e) => scan(e, var, u),
            Stmt::For { iterable, body, .. } => {
                u.has_jump_or_loop = true;
                scan(iterable, var, u);
                scan_block(body, var, u);
            }
            Stmt::While { cond, body } => {
                u.has_jump_or_loop = true;
                scan(cond, var, u);
                scan_block(body, var, u);
            }
        }
        if let Stmt::Set { name, .. } = s {
            if name == var {
                u.count += 2;
            }
        }
    }
    if let Some(t) = &b.tail {
        scan(t, var, u);
    }
}

fn scan(e: &Expr, var: &str, u: &mut Usage) {
    match &e.kind {
        ExprKind::Int(_) | ExprKind::Bool(_) | ExprKind::Text(_) | ExprKind::Unit => {}
        ExprKind::Name(n) => {
            if n == var {
                u.count += 1;
            }
        }
        ExprKind::List(items) => items.iter().for_each(|i| scan(i, var, u)),
        ExprKind::Call { args, .. } | ExprKind::Variant { args, .. } => args.iter().for_each(|a| scan(a, var, u)),
        ExprKind::Index { target, index } => {
            scan(target, var, u);
            scan(index, var, u);
        }
        ExprKind::Field { target, .. } => scan(target, var, u),
        ExprKind::Unary { operand, .. } => scan(operand, var, u),
        ExprKind::Binary { left, right, .. } => {
            scan(left, var, u);
            scan(right, var, u);
        }
        ExprKind::If { cond, then_block, else_branch } => {
            scan(cond, var, u);
            scan_block(then_block, var, u);
            if let Some(e) = else_branch {
                scan(e, var, u);
            }
        }
        ExprKind::Block(b) => scan_block(b, var, u),
        ExprKind::Match { scrutinee, arms } => {
            scan(scrutinee, var, u);
            for a in arms {
                scan(&a.body, var, u);
            }
        }
        ExprKind::Record { fields, .. } => fields.iter().for_each(|f| scan(&f.value, var, u)),
        ExprKind::Return(v) => {
            u.has_jump_or_loop = true;
            if let Some(v) = v {
                scan(v, var, u);
            }
        }
        ExprKind::Break | ExprKind::Continue => u.has_jump_or_loop = true,
    }
}

impl<'a> Gen<'a> {
    fn ty(&self, e: &Expr) -> &Type {
        &self.types[e.id]
    }

    fn loc(&self, span: Span) -> String {
        let path = &self.files[span.file].path;
        rust_string(&format!("{}:{}:{} in function `{}`", path, span.line, span.col, self.fn_name))
    }

    fn fresh(&mut self) -> String {
        self.tmp += 1;
        format!("t{}", self.tmp)
    }

    fn function(&mut self, f: &Function) -> String {
        self.fn_name = f.name.clone();
        self.tmp = 0;
        let mut out = String::new();
        for note in &f.notes {
            let _ = writeln!(out, "// note: {}", note.text.replace('\n', " "));
        }
        let params: Vec<String> = f
            .params
            .iter()
            .map(|p| format!("v_{}: {}", p.name, rust_type(&resolve_simple(&p.ty, self.defs))))
            .collect();
        let ret = rust_type(&resolve_simple(&f.ret, self.defs));
        let body = match &f.body.kind {
            ExprKind::Block(b) => self.block(b, 0),
            _ => format!("{{\n    {}\n}}", self.expr(&f.body, 1)),
        };
        let _ = writeln!(out, "fn f_{}({}) -> {} {}", f.name, params.join(", "), ret, body);
        out
    }

    fn block(&mut self, b: &Block, ind: usize) -> String {
        let mut out = String::from("{\n");
        for s in &b.stmts {
            let line = self.stmt(s, ind + 1);
            let _ = writeln!(out, "{}{}", pad(ind + 1), line);
        }
        if let Some(t) = &b.tail {
            let e = self.expr(t, ind + 1);
            let _ = writeln!(out, "{}{}", pad(ind + 1), e);
        }
        out.push_str(&pad(ind));
        out.push('}');
        out
    }

    fn stmt(&mut self, s: &Stmt, ind: usize) -> String {
        match s {
            Stmt::Let { name, value, mutable, .. } => {
                let v = self.expr(value, ind);
                match name {
                    None => format!("let _ = {};", v),
                    Some(n) => {
                        let t = self.ty(value).clone();
                        let m = if *mutable { "mut " } else { "" };
                        if t == Type::Never {
                            format!("let {}v_{} = {};", m, n, v)
                        } else {
                            format!("let {}v_{}: {} = {};", m, n, rust_type(&t), v)
                        }
                    }
                }
            }
            Stmt::Set { name, value, .. } => {
                let mut usage = Usage::default();
                scan(value, name, &mut usage);
                let movable = matches!(self.ty(value), Type::Text | Type::List(_));
                if movable && usage.count == 1 && !usage.has_jump_or_loop {
                    self.take_var = Some(name.clone());
                }
                let v = self.expr(value, ind);
                self.take_var = None;
                format!("v_{} = {};", name, v)
            }
            Stmt::For { var, iterable, body, .. } => {
                let it = self.expr(iterable, ind);
                let b = self.block(body, ind);
                format!("for v_{} in t_iter({}) {}", var, it, b)
            }
            Stmt::While { cond, body } => {
                let c = self.expr(cond, ind);
                let b = self.block(body, ind);
                format!("while {} {}", c, b)
            }
            Stmt::Expr(e) => format!("{};", self.expr(e, ind)),
        }
    }

    fn expr(&mut self, e: &Expr, ind: usize) -> String {
        match &e.kind {
            ExprKind::Int(v) => {
                if *v == i64::MIN {
                    "i64::MIN".into()
                } else if *v < 0 {
                    format!("({}i64)", v)
                } else {
                    format!("{}i64", v)
                }
            }
            ExprKind::Bool(b) => b.to_string(),
            ExprKind::Text(s) => format!("t_text({})", rust_string(s)),
            ExprKind::Unit => "()".into(),
            ExprKind::Name(n) => {
                if self.take_var.as_deref() == Some(n.as_str()) {
                    self.take_var = None;
                    format!("std::mem::take(&mut v_{})", n)
                } else {
                    format!("v_{}.clone()", n)
                }
            }
            ExprKind::List(items) => {
                if items.is_empty() {
                    let elem = match self.ty(e) {
                        Type::List(t) => rust_type(t),
                        _ => "()".into(),
                    };
                    format!("Rc::new(Vec::<{}>::new())", elem)
                } else {
                    let parts: Vec<String> = items.iter().map(|i| self.expr(i, ind)).collect();
                    format!("Rc::new(vec![{}])", parts.join(", "))
                }
            }
            ExprKind::Call { name, args, .. } => self.call(name, args, e.span, ind),
            ExprKind::Index { target, index } => {
                let t = self.expr(target, ind);
                let i = self.expr(index, ind);
                format!("t_index(&{}, {}, {})", t, i, self.loc(e.span))
            }
            ExprKind::Field { target, name, .. } => {
                let t = self.expr(target, ind);
                format!("({}).f_{}.clone()", t, name)
            }
            ExprKind::Unary { op, operand } => {
                let o = self.expr(operand, ind);
                match op {
                    UnaryOp::Neg => format!("t_neg({}, {})", o, self.loc(e.span)),
                    UnaryOp::Not => format!("(!{})", o),
                }
            }
            ExprKind::Binary { op, op_span, left, right } => {
                let is_text = *self.ty(e) == Type::Text;
                let l = self.expr(left, ind);
                let r = self.expr(right, ind);
                let loc = self.loc(*op_span);
                match op {
                    BinaryOp::Add if is_text => format!("t_concat({}, {})", l, r),
                    BinaryOp::Add => format!("t_add({}, {}, {})", l, r, loc),
                    BinaryOp::Sub => format!("t_sub({}, {}, {})", l, r, loc),
                    BinaryOp::Mul => format!("t_mul({}, {}, {})", l, r, loc),
                    BinaryOp::Div => format!("t_div({}, {}, {})", l, r, loc),
                    BinaryOp::Rem => format!("t_rem({}, {}, {})", l, r, loc),
                    BinaryOp::Eq => format!("({} == {})", l, r),
                    BinaryOp::NotEq => format!("({} != {})", l, r),
                    BinaryOp::Lt => format!("({} < {})", l, r),
                    BinaryOp::LtEq => format!("({} <= {})", l, r),
                    BinaryOp::Gt => format!("({} > {})", l, r),
                    BinaryOp::GtEq => format!("({} >= {})", l, r),
                    BinaryOp::And => format!("({} && {})", l, r),
                    BinaryOp::Or => format!("({} || {})", l, r),
                }
            }
            ExprKind::If { cond, then_block, else_branch } => {
                let c = self.expr(cond, ind);
                let t = self.block(then_block, ind);
                match else_branch {
                    None => format!("if {} {}", c, t),
                    Some(eb) => {
                        let el = self.expr(eb, ind);
                        format!("if {} {} else {}", c, t, el)
                    }
                }
            }
            ExprKind::Block(b) => self.block(b, ind),
            ExprKind::Match { scrutinee, arms } => self.match_expr(scrutinee, arms, ind),
            ExprKind::Record { type_name, fields, .. } => {
                let parts: Vec<String> = fields.iter().map(|f| format!("f_{}: {}", f.name, self.expr(&f.value, ind))).collect();
                format!("Rc::new(T_{} {{ {} }})", type_name, parts.join(", "))
            }
            ExprKind::Variant { type_name, variant, args, .. } => {
                if args.is_empty() {
                    format!("Rc::new(T_{}::V_{})", type_name, variant)
                } else {
                    let parts: Vec<String> = args.iter().map(|a| self.expr(a, ind)).collect();
                    format!("Rc::new(T_{}::V_{}({}))", type_name, variant, parts.join(", "))
                }
            }
            ExprKind::Return(v) => match v {
                Some(v) => format!("return {}", self.expr(v, ind)),
                None => "return ()".into(),
            },
            ExprKind::Break => "break".into(),
            ExprKind::Continue => "continue".into(),
        }
    }

    fn match_expr(&mut self, scrutinee: &Expr, arms: &[Arm], ind: usize) -> String {
        let st = self.ty(scrutinee).clone();
        let s = self.expr(scrutinee, ind);
        let head = match &st {
            Type::Named(_) => format!("match &*({})", s),
            Type::Text => format!("match ({}).as_str()", s),
            _ => format!("match {}", s),
        };
        let mut out = format!("{} {{\n", head);
        for arm in arms {
            let mut prefix = String::new();
            let pat = match &arm.pattern.kind {
                PatternKind::Wildcard => "_".to_string(),
                PatternKind::Int(v) => {
                    if *v == i64::MIN {
                        "i64::MIN".into()
                    } else {
                        v.to_string()
                    }
                }
                PatternKind::Text(t) => rust_string(t),
                PatternKind::Bool(b) => b.to_string(),
                PatternKind::Variant { type_name, variant, bindings } => {
                    let has_fields = match self.defs.get(type_name) {
                        Some(TypeDef::Enum { variants }) => variants.iter().find(|(n, _)| n == variant).map_or(false, |(_, f)| !f.is_empty()),
                        _ => false,
                    };
                    if !has_fields {
                        format!("T_{}::V_{}", type_name, variant)
                    } else {
                        let mut parts = Vec::new();
                        for (b, _) in bindings {
                            match b {
                                None => parts.push("_".to_string()),
                                Some(name) => {
                                    let tmp = self.fresh();
                                    let _ = write!(prefix, "let v_{} = {}.clone(); ", name, tmp);
                                    parts.push(tmp);
                                }
                            }
                        }
                        format!("T_{}::V_{}({})", type_name, variant, parts.join(", "))
                    }
                }
            };
            let body = self.expr(&arm.body, ind + 1);
            let _ = writeln!(out, "{}{} => {{ {}{} }}", pad(ind + 1), pat, prefix, body);
        }
        out.push_str(&pad(ind));
        out.push('}');
        out
    }

    fn call(&mut self, name: &str, args: &[Expr], span: Span, ind: usize) -> String {
        let a: Vec<String> = args.iter().map(|x| self.expr(x, ind)).collect();
        let loc = self.loc(span);
        let arg_ty = |i: usize| self.types[args[i].id].clone();
        match name {
            "print" => format!("t_print({})", a[0]),
            "print_error" => format!("t_print_error({})", a[0]),
            "to_text" => match arg_ty(0) {
                Type::Bool => format!("t_bool_to_text({})", a[0]),
                _ => format!("t_int_to_text({})", a[0]),
            },
            "length" => match arg_ty(0) {
                Type::Text => format!("t_text_length(&{})", a[0]),
                _ => format!("t_list_length(&{})", a[0]),
            },
            "append" => format!("t_append({}, {})", a[0], a[1]),
            "concat" => format!("t_concat_lists({}, {})", a[0], a[1]),
            "slice" => format!("t_slice({}, {}, {}, {})", a[0], a[1], a[2], loc),
            "replace_at" => format!("t_replace_at({}, {}, {}, {})", a[0], a[1], a[2], loc),
            "range" => format!("t_range({}, {}, {})", a[0], a[1], loc),
            "code_points" => format!("t_code_points(&{})", a[0]),
            "from_code_point" => format!("t_from_code_point({}, {})", a[0], loc),
            "from_code_points" => format!("t_from_code_points(&{}, {})", a[0], loc),
            "join" => format!("t_join(&{}, &{})", a[0], a[1]),
            "read_file" => format!("t_read_file({}, {})", a[0], loc),
            "write_file" => format!("t_write_file({}, {}, {})", a[0], a[1], loc),
            "args" => format!("t_args({})", loc),
            "exit" => format!("t_exit({}, {})", a[0], loc),
            "fail" => format!("t_user_fail({}, {})", a[0], loc),
            "file_exists" => format!("t_file_exists({})", a[0]),
            "environment_variable" => format!("t_environment_variable({})", a[0]),
            "run_process" => format!("t_run_process({}, {})", a[0], a[1]),
            "rgb" => format!("t_rgb({}, {}, {}, {})", a[0], a[1], a[2], loc),
            _ => format!("f_{}({})", name, a.join(", ")),
        }
    }
}

/// Resolve a type expression that the checker already validated.
fn resolve_simple(te: &TypeExpr, defs: &BTreeMap<String, TypeDef>) -> Type {
    match te.name.as_str() {
        "Int" => Type::Int,
        "Bool" => Type::Bool,
        "Text" => Type::Text,
        "Unit" => Type::Unit,
        "List" => Type::List(Box::new(te.args.first().map_or(Type::Unknown, |a| resolve_simple(a, defs)))),
        n if defs.contains_key(n) => Type::Named(n.to_string()),
        _ => Type::Unknown,
    }
}
